let current = localStorage.getItem('vestra.lang') || (navigator.language?.startsWith('he') ? 'he' : 'en');

export const t = (key) => DICT[current][key] ?? DICT.en[key] ?? key;
export const lang = () => current;
export const isHe = () => current === 'he';
/** Pick the `_he` or `_en` variant of an AI-returned field. */
export const pick = (obj, base) => {
  if (!obj) return '';
  return obj[`${base}_${current}`] || obj[`${base}_en`] || obj[`${base}_he`] || obj[base] || '';
};

export function setLang(l) {
  current = l;
  localStorage.setItem('vestra.lang', l);
  document.documentElement.lang = l;
  document.documentElement.dir = DICT[l].dir;
}

export function applyStaticText(root = document) {
  root.querySelectorAll('[data-t]').forEach(el => { el.textContent = t(el.dataset.t); });
  root.querySelectorAll('[data-tph]').forEach(el => { el.placeholder = t(el.dataset.tph); });
  root.querySelectorAll('[data-taria]').forEach(el => { el.setAttribute('aria-label', t(el.dataset.taria)); });
}

export function greeting() {
  const h = new Date().getHours();
  if (h < 5)  return t('greet_night');
  if (h < 12) return t('greet_morning');
  if (h < 17) return t('greet_noon');
  if (h < 22) return t('greet_evening');
  return t('greet_night');
}
